#!/usr/bin/env node
// ════════════════════════════════════════════════════════
//  DoubleCup Studios — build-share-pages.js
//
//  Link previews (Discord, WhatsApp, X, Facebook…) read the <meta> tags of the
//  HTML WITHOUT running JavaScript, and the "#devlog/<id>" part of a URL is never
//  sent to the server. So every "/#devlog/<id>" link shows the home page preview.
//
//  This script creates one tiny static page per post:
//      devlog/<id>/index.html   →  https://doublecup.vercel.app/devlog/<id>/
//  with the post's title, summary and image as Open Graph tags. People who open
//  it are sent straight to the post on the main page (/#devlog/<id>).
//
//  Run after adding/editing a post, then commit the generated "devlog/" folder:
//      node tools/build-share-pages.js
// ════════════════════════════════════════════════════════
const fs   = require('fs');
const path = require('path');
const vm   = require('vm');

const SITE_URL   = 'https://doublecup.vercel.app';   // no trailing slash
const SHARE_LANG = 'pt';                             // language of the preview text: 'pt' or 'en'
const DEFAULT_IMAGE = 'assets/images/gallery/key-art.jpg';

const ROOT    = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'devlog');
const MARKER  = '<!-- generated by tools/build-share-pages.js -->';

// ── Load the posts exactly as the browser does ──
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'assets/js/devlog-data.js'), 'utf8'), sandbox);
const posts = (sandbox.window.DEVLOG_POSTS || []).filter(p => p && p.id && p.date);

const esc = s => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const loc = f => (f == null ? '' : typeof f === 'string' ? f : (f[SHARE_LANG] ?? f.en ?? f.pt ?? ''));
const abs = p => /^https?:\/\//.test(p) ? p : `${SITE_URL}/${p.replace(/^\/+/, '')}`;

function imageSize(file) {
  // Reads width/height of JPEG or PNG so previews render at the right size
  try {
    const b = fs.readFileSync(path.join(ROOT, file));
    if (b[0] === 0x89 && b[1] === 0x50) return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
    let i = 2;
    while (i < b.length) {
      if (b[i] !== 0xFF) { i++; continue; }
      const m = b[i + 1];
      if (m >= 0xC0 && m <= 0xCF && ![0xC4, 0xC8, 0xCC].includes(m)) return { h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7) };
      i += 2 + b.readUInt16BE(i + 2);
    }
  } catch (e) { /* unknown size is fine */ }
  return null;
}

// ── Clean old generated pages (only folders this script created) ──
if (fs.existsSync(OUT_DIR)) {
  for (const d of fs.readdirSync(OUT_DIR)) {
    const f = path.join(OUT_DIR, d, 'index.html');
    if (fs.existsSync(f) && fs.readFileSync(f, 'utf8').includes(MARKER)) fs.rmSync(path.join(OUT_DIR, d), { recursive: true });
  }
}

const ids = new Set();
for (const p of posts) {
  if (!/^[a-z0-9-]+$/i.test(p.id)) { console.warn(`! skipped "${p.id}": id must use only letters, numbers and dashes`); continue; }
  if (ids.has(p.id)) { console.warn(`! skipped duplicate id "${p.id}"`); continue; }
  ids.add(p.id);

  const img     = p.cover || (Array.isArray(p.images) && p.images[0] && p.images[0].src) || DEFAULT_IMAGE;
  const size    = imageSize(img);
  const title   = `${loc(p.title)}${p.version ? ` (${p.version})` : ''} · DoubleCup Studios`;
  const desc    = loc(p.summary) || 'Devlog · DoubleCup Studios';
  const url     = `${SITE_URL}/devlog/${p.id}/`;
  const target  = `../../#devlog/${p.id}`;

  const html = `<!DOCTYPE html>
${MARKER}
<html lang="${SHARE_LANG === 'pt' ? 'pt-BR' : 'en'}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}">
  <meta name="theme-color" content="#9B30FF">
  <link rel="canonical" href="${esc(url)}">
  <link rel="icon" type="image/png" href="../../assets/images/favicon-64.png">

  <meta property="og:type"        content="article">
  <meta property="og:site_name"   content="DoubleCup Studios">
  <meta property="og:title"       content="${esc(title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url"         content="${esc(url)}">
  <meta property="og:image"       content="${esc(abs(img))}">${size ? `
  <meta property="og:image:width"  content="${size.w}">
  <meta property="og:image:height" content="${size.h}">` : ''}
  <meta property="article:published_time" content="${esc(p.date)}">
  <meta name="twitter:card"        content="summary_large_image">
  <meta name="twitter:title"       content="${esc(title)}">
  <meta name="twitter:description" content="${esc(desc)}">
  <meta name="twitter:image"       content="${esc(abs(img))}">

  <meta http-equiv="refresh" content="0; url=${esc(target)}">
  <script>location.replace(${JSON.stringify(target)});</script>
  <style>body{background:#050008;color:#C77DFF;font-family:monospace;display:grid;place-items:center;min-height:100vh;margin:0}a{color:#C77DFF}</style>
</head>
<body>
  <p><a href="${esc(target)}">${esc(loc(p.title))} &rarr;</a></p>
</body>
</html>
`;
  fs.mkdirSync(path.join(OUT_DIR, p.id), { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, p.id, 'index.html'), html);
  console.log(`✓ devlog/${p.id}/  →  ${abs(img)}`);
}
console.log(`${ids.size} share page(s) generated.`);
